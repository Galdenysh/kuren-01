/**
 * Учебный текст. Одна и та же строка при каждом чтении.
 * Фразы разделены переводом строки. Первая — не короче остальных:
 * тест дописывает её последние символы.
 */
const CORPUS = `мама мыла раму
папа спал дома
кот сидел тихо`

/** Зафиксированный корпус из нескольких коротких фраз. */
export function readCorpus(): string {
  return CORPUS
}
